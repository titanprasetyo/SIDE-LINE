-- ==============================================================================
-- TABEL REVIEWS (Ulasan & Testimonial Pelanggan)
-- ==============================================================================
create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  name text not null,
  rating int not null default 5 check (rating >= 1 and rating <= 5),
  comment text not null,
  tag text default 'Pengunjung',
  is_published boolean default true,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Row Level Security (RLS)
alter table public.reviews enable row level security;

-- Publik bisa membaca ulasan yang dipublikasikan
drop policy if exists "Allow public read reviews" on public.reviews;
create policy "Allow public read reviews" on public.reviews
  for select using (is_published = true);

-- Publik (pelanggan) bisa menambahkan ulasan sendiri
drop policy if exists "Allow public insert reviews" on public.reviews;
create policy "Allow public insert reviews" on public.reviews
  for insert with check (true);

-- Admin punya akses penuh
drop policy if exists "Allow admin all reviews" on public.reviews;
create policy "Allow admin all reviews" on public.reviews
  for all to authenticated using (true) with check (true);
